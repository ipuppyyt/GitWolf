#!/usr/bin/env python3
"""Regenerates src/GitWolf.App/Views/LanguageLogos.cs from the Simple Icons (CC0) path data that the macOS
app embeds. Reads apple/ without changing it. WinUI's path parser needs every number separated, including
the two one-digit flags of an arc, which SVG allows to run together."""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "apple/Sources/GitWolfApp/LanguageLogos.swift"
OUTPUT = ROOT / "windows/src/GitWolf.App/Views/LanguageLogos.cs"

NUMBER = re.compile(r"[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?")
SIZES = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6, "S": 4, "Q": 4, "T": 2, "A": 7, "Z": 0}


def normalise(path):
    out, position, command, index = [], 0, "", 0
    while position < len(path):
        char = path[position]
        if char in " ,\t\n":
            position += 1
        elif char.isalpha() and char.upper() in SIZES:
            command, index = char, 0
            out.append(char)
            position += 1
        elif command.upper() == "A" and index % 7 in (3, 4):
            if char not in "01":
                sys.exit(f"bad arc flag at {position}")
            out.append(char)
            position, index = position + 1, index + 1
        else:
            match = NUMBER.match(path, position)
            if not match or not command:
                sys.exit(f"unreadable path at {position}: {path[position:position + 12]!r}")
            out.append(match.group())
            position, index = match.end(), index + 1
    return " ".join(out)


def main():
    logos = re.findall(r'"([^"]+)": "([^"]+)",', SOURCE.read_text(encoding="utf-8"))
    if not logos:
        sys.exit("no logos found")
    lines = [
        "namespace GitWolf.App.Views;", "",
        "// Generated by windows/tools/embed-logos.py from Simple Icons (CC0, https://simpleicons.org).",
        "// Do not edit by hand. Path data on a 24x24 grid, keyed by Simple Icons slug.",
        "internal static class LanguageLogos", "{",
        "    public static readonly IReadOnlyDictionary<string, string> Paths = new Dictionary<string, string>", "    {",
    ]
    lines += [f'        ["{slug}"] = "F1 {normalise(path)}",' for slug, path in logos]
    lines += ["    };", "}", ""]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(logos)} logos")


main()
